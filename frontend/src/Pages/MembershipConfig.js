export function createBuilderField(type = "text") {
  const id = `field_${crypto.randomUUID().replaceAll("-", "").slice(0, 16)}`;
  return {
    id,
    type,
    label: type === "section" ? "Ny innholdsboks" : "Nytt felt",
    required: false,
    ...(type === "select" ? { options: ["Alternativ 1"] } : {}),
    ...(type === "section" ? { content: "" } : {}),
  };
}

